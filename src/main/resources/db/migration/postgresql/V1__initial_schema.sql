CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    department VARCHAR(255),
    cgpa DOUBLE PRECISION,
    skills VARCHAR(3000),
    account_role VARCHAR(20)
);

CREATE TABLE career_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_type VARCHAR(255) NOT NULL,
    domains VARCHAR(1000),
    priorities VARCHAR(1000),
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    target_career VARCHAR(255),
    target_date DATE
);

CREATE TABLE user_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(255) NOT NULL,
    confidence INTEGER NOT NULL,
    last_practiced DATE,
    proficiency VARCHAR(255) NOT NULL CHECK (proficiency IN ('BEGINNER','INTERMEDIATE','ADVANCED','EXPERT')),
    skill_name VARCHAR(255) NOT NULL,
    verification_status VARCHAR(255) NOT NULL CHECK (verification_status IN ('SELF_REPORTED','PROJECT_BACKED','CERTIFICATION_BACKED','ASSESSMENT_VERIFIED')),
    user_id BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (user_id, skill_name)
);
CREATE INDEX idx_user_skills_user_id ON user_skills(user_id);

CREATE TABLE skill_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    description VARCHAR(1000),
    title VARCHAR(120) NOT NULL,
    type VARCHAR(255) NOT NULL CHECK (type IN ('PROJECT','INTERNSHIP','CERTIFICATION','COURSE','WORK_EXPERIENCE','ASSESSMENT')),
    url VARCHAR(500),
    user_skill_id BIGINT NOT NULL REFERENCES user_skills(id)
);
CREATE INDEX idx_skill_evidence_user_skill_id ON skill_evidence(user_skill_id);

CREATE TABLE roadmap_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_name VARCHAR(255) NOT NULL,
    completed BOOLEAN NOT NULL,
    completed_at TIMESTAMP,
    description VARCHAR(1200) NOT NULL,
    phase VARCHAR(255) NOT NULL,
    skill_name VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    week_index INTEGER NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id),
    UNIQUE (user_id, career_name, skill_name, phase)
);
CREATE INDEX idx_roadmap_tasks_user_id ON roadmap_tasks(user_id);

CREATE TABLE career_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    demo_url VARCHAR(255),
    description VARCHAR(2000),
    duration VARCHAR(255),
    featured BOOLEAN NOT NULL,
    github_url VARCHAR(255),
    name VARCHAR(120) NOT NULL,
    outcome VARCHAR(1000),
    project_type VARCHAR(255),
    role VARCHAR(255),
    skills VARCHAR(1000),
    technologies VARCHAR(800),
    user_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX idx_career_projects_user_id ON career_projects(user_id);

CREATE TABLE job_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applied_date DATE,
    company VARCHAR(255) NOT NULL,
    job_url VARCHAR(255),
    notes VARCHAR(1200),
    role VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL CHECK (status IN ('SAVED','APPLIED','ASSESSMENT','INTERVIEW','OFFER','REJECTED','WITHDRAWN')),
    user_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX idx_job_applications_user_id ON job_applications(user_id);

CREATE TABLE interview_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer VARCHAR(5000),
    career_name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    question VARCHAR(800) NOT NULL,
    self_rating INTEGER NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX idx_interview_attempts_user_id ON interview_attempts(user_id);
